package ui

import (
	"time"

	tea "charm.land/bubbletea/v2"

	"github.com/gammons/slk/internal/ui/styles"
)

// ThemeWatchMsg is the periodic tick that checks the custom themes
// directory for changes.
type ThemeWatchMsg struct{}

// themeWatchInterval is how often the themes directory is checked. One
// directory listing every couple of seconds is negligible.
const themeWatchInterval = 2 * time.Second

func themeWatchTick() tea.Cmd {
	return tea.Tick(themeWatchInterval, func(time.Time) tea.Msg { return ThemeWatchMsg{} })
}

// reduceThemeWatch reloads the custom themes when a theme file was added,
// removed or rewritten, and re-applies the active theme if it is one of
// them — so a theme file regenerated by another program (a desktop theme
// hook, an editor) shows up live.
var reduceThemeWatch reducerFunc = func(a *App, msg tea.Msg) (tea.Cmd, bool) {
	if _, ok := msg.(ThemeWatchMsg); !ok {
		return nil, false
	}
	if a.themesFS == nil {
		return nil, true
	}
	if styles.ReloadCustomThemesIfChanged(a.themesFS) {
		a.SetThemeItems(styles.ThemeNames())
		if styles.ActiveIsCustom() {
			styles.Reapply()
			a.refreshThemedViews()
		}
	}
	return themeWatchTick(), true
}
